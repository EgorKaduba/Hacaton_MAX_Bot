async def _load_context(session: AsyncSession, max_user_id: int) -> str:
    user = await session.scalar(
        select(User).where(User.max_user_id == max_user_id)
    )
    if not user:
        return "Данных о квитанциях пользователя нет."

    receipts = await session.scalars(
        select(Receipt)
        .where(Receipt.user_id == user.id)
        .order_by(Receipt.period_year.desc(), Receipt.period_month.desc())
        .limit(3)
        .options(selectinload(Receipt.service_charges))
    )
    receipts = receipts.all()
    if not receipts:
        return "У пользователя нет загруженных квитанций."

    lines = []
    for r in receipts:
        lines.append(f"\nКвитанция за {r.period_month} {r.period_year}:")
        lines.append(f"  Итого: {r.total_without_insurance} руб.")
        lines.append("  Услуги:")
        for sc in r.service_charges:
            lines.append(
                f"    - {sc.service_name}: {sc.total} руб."
                f" (объём {sc.volume}, тариф {sc.tariff})"
            )
    return "\n".join(lines)


async def ask_ai(
    session: AsyncSession,
    max_user_id: int,
    message: str,
) -> str:
    if not settings.LLM_ENABLED:
        return "AI-помощник временно отключён."

    context = await _load_context(session, max_user_id)

    client = AsyncOpenAI(
        api_key=settings.LLM_API_KEY,
        base_url=settings.LLM_BASE_URL,
    )

    try:
        response = await client.chat.completions.create(
            model=settings.LLM_MODEL,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "system", "content": f"Данные квитанций:\n{context}"},
                {"role": "user", "content": message},
            ],
            temperature=0.15,
        )
        return response.choices[0].message.content or "Не удалось получить ответ."
    except Exception as e:
        logger.exception("LLM error: %s", e)
        return "Не удалось получить ответ от AI-помощника. Попробуйте позже."